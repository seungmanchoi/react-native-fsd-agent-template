#!/usr/bin/env node
// Regenerates the Codex copies of the harness from the Claude sources, which stay the
// single source of truth (hand-edited copies drifted for months):
//   .claude/agents/<name>.md  ->  .codex/agents/<name>.toml
//   .claude/skills/<name>/    ->  .agents/skills/<name>/
// Run after editing any agent or skill:  npm run sync:codex
// `--check` writes nothing and exits 1 when the copies are stale (used by npm run verify).
import {
  cpSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const check = process.argv.includes('--check');
const HEADER =
  '# GENERATED by scripts/sync-codex-harness.mjs from .claude/agents — edit the source, then re-run.\n';
const OUTPUTS = ['.codex/agents', '.agents/skills'];

function splitFrontmatter(markdown, file) {
  const match = markdown.match(/^---\n([\s\S]*?)\n---\n/);
  if (!match) throw new Error(`${file}: missing frontmatter`);
  const meta = {};
  for (const line of match[1].split('\n')) {
    const i = line.indexOf(':');
    if (i > 0)
      meta[line.slice(0, i).trim()] = line
        .slice(i + 1)
        .trim()
        .replace(/^"(.*)"$/, '$1');
  }
  if (!meta.name || !meta.description)
    throw new Error(`${file}: frontmatter needs name + description`);
  return { meta, body: markdown.slice(match[0].length).replace(/^\n+/, '') };
}

function generate(out) {
  // Agents → TOML. The body goes into a multi-line *literal* string ('''), so backslashes
  // and quotes in the markdown need no escaping; JSON string syntax is valid TOML.
  const agentsSrc = join(root, '.claude/agents');
  const agentsOut = join(out, '.codex/agents');
  mkdirSync(agentsOut, { recursive: true });
  for (const file of readdirSync(agentsSrc).filter((f) => f.endsWith('.md'))) {
    const { meta, body } = splitFrontmatter(readFileSync(join(agentsSrc, file), 'utf8'), file);
    if (body.includes("'''"))
      throw new Error(`${file}: body contains ''' (cannot be a TOML literal string)`);
    const toml = `${HEADER}name = ${JSON.stringify(meta.name)}\ndescription = ${JSON.stringify(meta.description)}\ndeveloper_instructions = '''\n${body.trimEnd()}\n'''\n`;
    writeFileSync(join(agentsOut, `${meta.name}.toml`), toml);
  }

  // Skills → verbatim copies (Codex skills use the same SKILL.md frontmatter).
  const skillsSrc = join(root, '.claude/skills');
  const skillsOut = join(out, '.agents/skills');
  mkdirSync(skillsOut, { recursive: true });
  for (const name of readdirSync(skillsSrc)) {
    if (!existsSync(join(skillsSrc, name, 'SKILL.md'))) continue;
    splitFrontmatter(readFileSync(join(skillsSrc, name, 'SKILL.md'), 'utf8'), `${name}/SKILL.md`);
    cpSync(join(skillsSrc, name), join(skillsOut, name), {
      recursive: true,
      filter: (src) => !src.endsWith('.DS_Store'),
    });
  }
}

function listFiles(dir, base = dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = join(dir, e.name);
    if (e.name === '.DS_Store') return [];
    return e.isDirectory() ? listFiles(p, base) : [relative(base, p)];
  });
}

// Build into a temp dir first so a bad source never leaves the copies half-deleted.
const staging = mkdtempSync(join(tmpdir(), 'sync-codex-'));
try {
  generate(staging);
  if (check) {
    const stale = OUTPUTS.flatMap((dir) => {
      const want = listFiles(join(staging, dir));
      const have = listFiles(join(root, dir));
      const changed = want.filter(
        (f) =>
          !have.includes(f) ||
          readFileSync(join(staging, dir, f), 'utf8') !== readFileSync(join(root, dir, f), 'utf8'),
      );
      const extra = have.filter((f) => !want.includes(f));
      return [...changed, ...extra].map((f) => join(dir, f));
    });
    if (stale.length) {
      console.error(
        `Codex harness copies are stale — run npm run sync:codex:\n  ${stale.join('\n  ')}`,
      );
      process.exitCode = 1; // not process.exit(): the finally block must remove the staging dir
    } else {
      console.log('Codex harness copies are in sync');
    }
  } else {
    for (const dir of OUTPUTS) {
      rmSync(join(root, dir), { recursive: true, force: true });
      cpSync(join(staging, dir), join(root, dir), { recursive: true });
    }
    console.log(
      `synced ${readdirSync(join(root, OUTPUTS[0])).length} agents, ${readdirSync(join(root, OUTPUTS[1])).length} skills`,
    );
  }
} finally {
  rmSync(staging, { recursive: true, force: true });
}
